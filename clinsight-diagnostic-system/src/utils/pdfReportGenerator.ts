import { jsPDF } from 'jspdf';
import {
  GeneratedReportRecord,
  PatientRecord,
  UnifiedAssessment,
} from '../types/clinical';

export interface ReportDraft {
  patient: PatientRecord;
  assessment: UnifiedAssessment;
  sourceDetails: string;
  extractedFindings: string[];
  aiObservations: string[];
  clinicianNotes: string;
  generatedBy: string;
}

export function buildAssessmentPdfBlob(draft: ReportDraft): {
  blob: Blob;
  fileName: string;
  record: Omit<GeneratedReportRecord, 'id'>;
} {
  const doc = new jsPDF({ unit: 'pt', format: 'letter' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 44;
  let y = 48;

  const checkPageBreak = (needed = 60) => {
    if (y + needed > doc.internal.pageSize.getHeight() - 56) {
      doc.addPage();
      y = 48;
    }
  };

  // Header Brand Bar (#071D35)
  doc.setFillColor(7, 29, 53);
  doc.rect(0, 0, pageWidth, 68, 'F');
  doc.setFillColor(25, 182, 178);
  doc.rect(0, 65, pageWidth, 3, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.text('ClinSight Diagnostic System', margin, 34);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(180, 200, 231);
  doc.text('Clinical Decision Support Assessment Report', margin, 51);

  const generatedStamp = new Date().toLocaleString();
  doc.text(`Generated: ${generatedStamp}`, pageWidth - margin, 51, { align: 'right' });

  y = 92;

  // Patient Identity Box
  doc.setFillColor(244, 247, 251);
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(margin, y, pageWidth - margin * 2, 76, 4, 4, 'FD');

  doc.setTextColor(7, 29, 53);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text(`Patient: ${draft.patient.name}`, margin + 14, y + 20);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(68, 71, 77);
  doc.text(
    `Patient ID: ${draft.patient.patientCode ?? draft.patient.id}   |   MRN: ${draft.patient.mrn}   |   Age/Sex: ${draft.patient.age}y ${draft.patient.sex}`,
    margin + 14,
    y + 38
  );
  doc.text(
    `Allergies: ${draft.patient.allergies.join(', ')}   |   Unit/Bed: ${draft.patient.bed}`,
    margin + 14,
    y + 54
  );
  doc.text(
    `Existing Conditions: ${(draft.patient.existingConditions ?? [draft.patient.chiefComplaint]).join(', ')}`,
    margin + 14,
    y + 68
  );

  y += 96;

  // Assessment Metadata Strip
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(7, 29, 53);
  doc.text('Assessment Overview', margin, y);
  y += 16;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(24, 28, 31);
  const metaLines = [
    `Analysis Type: ${draft.assessment.analysisType} (${draft.assessment.modalityOrCategory})`,
    `Source / Study Details: ${draft.sourceDetails}`,
    `Priority Classification (Assistive): ${draft.assessment.priority} Priority   |   Confidence: ${draft.assessment.confidence.toFixed(1)}%`,
    `Clinician Review Status: ${draft.assessment.reviewStatus}   |   Reviewed/Generated By: ${draft.generatedBy}`,
    `Provenance: ${
      draft.assessment.provenance === 'functional_ai'
        ? `Functional AI (${draft.assessment.modelUsed ?? 'Gemini'})`
        : draft.assessment.provenance === 'statistical_ml'
        ? 'Statistical / ML Cohort Analysis'
        : 'Simulated Demonstration Baseline'
    }`,
  ];
  metaLines.forEach((line) => {
    const wrapped = doc.splitTextToSize(line, pageWidth - margin * 2);
    doc.text(wrapped, margin, y);
    y += wrapped.length * 13;
  });

  y += 10;

  // Extracted Clinical Findings
  checkPageBreak(80);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(7, 29, 53);
  doc.text('Extracted Clinical Findings', margin, y);
  y += 16;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(40, 44, 52);
  (draft.extractedFindings.length > 0
    ? draft.extractedFindings
    : ['No structured extracted facts attached.']).forEach((item) => {
    checkPageBreak(26);
    const lines = doc.splitTextToSize(`• ${item}`, pageWidth - margin * 2 - 8);
    doc.text(lines, margin + 4, y);
    y += lines.length * 13 + 2;
  });

  y += 10;

  // AI-Generated Observations
  checkPageBreak(80);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(0, 106, 103);
  doc.text('AI-Generated Observations (Decision Support)', margin, y);
  y += 16;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(40, 44, 52);
  (draft.aiObservations.length > 0
    ? draft.aiObservations
    : [draft.assessment.potentialFindings]).forEach((obs) => {
    checkPageBreak(26);
    const lines = doc.splitTextToSize(`• ${obs}`, pageWidth - margin * 2 - 8);
    doc.text(lines, margin + 4, y);
    y += lines.length * 13 + 2;
  });

  y += 10;

  // Clinician Notes
  checkPageBreak(60);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(7, 29, 53);
  doc.text('Clinician Notes & Verification', margin, y);
  y += 15;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  const noteText = draft.clinicianNotes.trim() || 'No clinician notes documented at report generation.';
  const noteLines = doc.splitTextToSize(noteText, pageWidth - margin * 2);
  doc.text(noteLines, margin, y);
  y += noteLines.length * 13 + 18;

  // Mandatory Medical Disclaimer Box
  checkPageBreak(70);
  doc.setFillColor(255, 251, 235);
  doc.setDrawColor(245, 158, 11);
  doc.roundedRect(margin, y, pageWidth - margin * 2, 52, 4, 4, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(146, 64, 14);
  doc.text('MEDICAL DECISION-SUPPORT DISCLAIMER', margin + 10, y + 15);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  const disclaimer = doc.splitTextToSize(
    'ClinSight is an assistive clinical decision-support prototype and is NOT an autonomous diagnostic system. All AI-generated observations, extracted values, and priority recommendations must be verified by a qualified healthcare professional against primary source records.',
    pageWidth - margin * 2 - 20
  );
  doc.text(disclaimer, margin + 10, y + 28);

  const safeCode = (draft.patient.patientCode ?? draft.patient.mrn).replace(/[^a-zA-Z0-9_-]/g, '');
  const fileName = `ClinSight_Report_${safeCode}_${Date.now()}.pdf`;
  const blob = doc.output('blob');

  return {
    blob,
    fileName,
    record: {
      patientId: draft.patient.id,
      assessmentId: draft.assessment.id,
      title: `${draft.assessment.analysisType} Assessment — ${draft.assessment.modalityOrCategory}`,
      analysisType: draft.assessment.analysisType,
      generatedAt: new Date().toISOString(),
      generatedBy: draft.generatedBy,
      priority: draft.assessment.priority,
      reviewStatus: draft.assessment.reviewStatus,
      fileName,
    },
  };
}
